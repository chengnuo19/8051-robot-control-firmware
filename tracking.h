#ifndef __TRACKING_H__
#define __TRACKING_H__

#include "config.h"

// 红外传感器初始化
void Tracking_Init(void);

// 读取当前红外传感器的原始状态 (以 4 位二进制形式返回，低4位对应 L2, L1, R1, R2)
u8 Tracking_ReadRaw(void);

// 根据红外探头的加权分布计算当前小车的水平轴偏差量 (Error)
// 返回值范围: -3 (偏左最远，需大向左打方向) 到 3 (偏右最远，需大向右打方向)
// 带有“失轨记忆”算法，如果冲出轨道会保留上次偏差方向，引导小车自动拉回。
s16 Tracking_GetError(void);

#endif /* __TRACKING_H__ */
