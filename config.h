#ifndef __CONFIG_H__
#define __CONFIG_H__

#include <reg52.h>

/* ========================================================================== */
/*                      1. 晶振与系统频率定义 (一键切换)                       */
/* ========================================================================== */
// ！！！请在此处选择你的板子晶振频率，保留一个定义，注释掉另一个 ！！！
#define OSC_FREQ_110592     // 常见电赛系统晶振 (9600波特率完全无误差)
// #define OSC_FREQ_12000   // 标准12MHz晶振 (串口波特率建议使用4800或9600，但12M下9600有误差，降到4800最安全)

#ifdef OSC_FREQ_110592
    #define FOSC 11059200UL // 11.0592 MHz
    #define UART_BAUD 9600  // 串口波特率使用 9600，通信流畅
#else
    #define FOSC 12000000UL // 12 MHz
    #define UART_BAUD 4800  // 串口波特率降为 4800，防乱码更安全
#endif

/* ========================================================================== */
/*                      2. 数据类型重定义 (方便书写)                          */
/* ========================================================================== */
typedef unsigned char u8;
typedef unsigned int  u16;
typedef unsigned long u32;

typedef signed char   s8;
typedef signed int    s16;
typedef signed long   s32;

/* ========================================================================== */
/*                      3. 引脚分配 (Pin Map) - 可根据实际接线修改             */
/* ========================================================================== */

/* --- A. 电机驱动引脚 (IN1-IN4 控制方向，ENA/ENB 控制PWM) --- */
sbit L_IN1 = P1^0;  // 左电机方向控制1
sbit L_IN2 = P1^1;  // 左电机方向控制2
sbit L_PWM = P1^4;  // 左电机使能/PWM输入 (对应TB6612的PWMA或L298N的ENA)

sbit R_IN1 = P1^2;  // 右电机方向控制1
sbit R_IN2 = P1^3;  // 右电机方向控制2
sbit R_PWM = P1^5;  // 右电机使能/PWM输入 (对应TB6612的PWMB或L298N的ENB)

/* --- B. 舵机引脚 (50Hz PWM，机械臂/云台) --- */
sbit SERVO1 = P1^6; // 舵机1 信号引脚
sbit SERVO2 = P1^7; // 舵机2 信号引脚

/* --- C. 红外循迹传感器引脚 --- */
sbit TRACK_L2 = P2^0; // 最左侧红外探头 (检测到黑线输出高/低)
sbit TRACK_L1 = P2^1; // 左内侧红外探头
sbit TRACK_R1 = P2^2; // 右内侧红外探头
sbit TRACK_R2 = P2^3; // 最右侧红外探头

/* --- D. HC-SR04 超声波测距引脚 --- */
sbit TRIG = P2^4; // 触发信号输入
sbit ECHO = P2^5; // 回响信号输出

/* --- E. OLED 屏幕引脚 (软件模拟I2C) --- */
sbit OLED_SCL = P2^6; // 时钟线
sbit OLED_SDA = P2^7; // 数据线

/* --- F. 串口引脚 (51单片机硬件固定引脚) --- */
// P3.0 - RXD (接 OpenMV 的 TX)
// P3.1 - TXD (接 OpenMV 的 RX)

/* ========================================================================== */
/*                      4. 循迹逻辑常数 (检测电平定义)                         */
/* ========================================================================== */
// 一般循迹传感器：白纸输出低电平(0)，黑线输出高电平(1)
// 如果您的模块相反（白纸1，黑线0），请将下面的定义反过来即可。
#define TRACK_WHITE 0   // 检测到白纸
#define TRACK_BLACK 1   // 检测到黑线

#endif /* __CONFIG_H__ */
