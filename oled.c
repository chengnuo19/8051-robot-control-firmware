/**
  * @brief  向 OLED 写入一条命令
  * @param  cmd  要写入的命令字
  * @retval 无
  */
static void OLED_WriteCommand(unsigned char cmd)
{
    OLED_I2C_Start();
    OLED_I2C_WriteByte(0x78); // OLED 的 I2C 写入地址 (SA0拉低时为0x78)
    OLED_I2C_WriteByte(0x00); // 0x00 代表接下来写入的是命令
    OLED_I2C_WriteByte(cmd);
    OLED_I2C_Stop();
}

/**
  * @brief  向 OLED 写入一个字节的数据
  * @param  dat  要写入的数据
  * @retval 无
  */
static void OLED_WriteData(unsigned char dat)
{
    OLED_I2C_Start();
    OLED_I2C_WriteByte(0x78); // OLED I2C 写入地址
    OLED_I2C_WriteByte(0x40); // 0x40 代表接下来写入的是数据
    OLED_I2C_WriteByte(dat);
    OLED_I2C_Stop();
}

