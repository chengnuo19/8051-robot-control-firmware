/**
  * @brief  设置 OLED 光标位置
  * @param  page  页地址 (0 ~ 7)
  * @param  col   列地址 (0 ~ 127)
  * @retval 无
  */
static void OLED_SetCursor(unsigned char page, unsigned char col)
{
    OLED_WriteCommand(0xB0 + page);                 // 设置页地址
    OLED_WriteCommand(0x10 + ((col & 0xF0) >> 4));  // 设置列高4位地址
    OLED_WriteCommand(0x00 + (col & 0x0F));         // 设置列低4位地址
}

/**
  * @brief  OLED 屏初始化配置 (SSD1306)
  * @param  无
  * @retval 无
  */
void OLED_Init(void)
{
    // OLED 引脚初始状态拉高
    OLED_SCL = 1;
    OLED_SDA = 1;

    // 上电防抖延时
    OLED_I2C_Delay();

    OLED_WriteCommand(0xAE); // 关闭显示
    
    OLED_WriteCommand(0xD5); // 设置时钟分频因子/振荡器频率
    OLED_WriteCommand(0x80);
    
    OLED_WriteCommand(0xA8); // 设置多路复用率
    OLED_WriteCommand(0x3F); // 64行 (1/64)
    
    OLED_WriteCommand(0xD3); // 设置显示偏移
    OLED_WriteCommand(0x00); // 无偏移
    
    OLED_WriteCommand(0x40); // 设置显示开始行 (0x40~0x7F)
    
    OLED_WriteCommand(0x8D); // 充电泵设置
    OLED_WriteCommand(0x14); // 开启充电泵
    
    OLED_WriteCommand(0x20); // 设置内存地址模式
    OLED_WriteCommand(0x02); // 页寻址模式
    
    OLED_WriteCommand(0xA1); // 段重映射 (0xA1左右翻转)
    OLED_WriteCommand(0xC8); // 行重映射 (0xC8上下翻转)
    
    OLED_WriteCommand(0xDA); // COM硬件引脚配置
    OLED_WriteCommand(0x12);
    
    OLED_WriteCommand(0x81); // 对比度控制
    OLED_WriteCommand(0xCF); // 亮度设定
    
    OLED_WriteCommand(0xD9); // 设置预充电周期
    OLED_WriteCommand(0xF1);
    
    OLED_WriteCommand(0xDB); // 设置VCOMH电压倍率
    OLED_WriteCommand(0x30);
    
    OLED_WriteCommand(0xA4); // 全屏显示开启 (A4:根据RAM内容显示，A5:全屏点亮)
    OLED_WriteCommand(0xA6); // 正常显示 (A6正常，A7反相显示)
    OLED_WriteCommand(0xAF); // 开启屏幕显示
    
    OLED_Clear();            // 清屏
}

/**
  * @brief  清空 OLED 屏幕上的内容
  * @param  无
  * @retval 无
  */
void OLED_Clear(void)
{
    unsigned char i, j;
    for (i = 0; i < 8; i++) // 8个页
    {
        OLED_SetCursor(i, 0);
        for (j = 0; j < 128; j++) // 每页128列全部填0
        {
            OLED_WriteData(0x00);
        }
    }
}

/**
  * @brief  在 OLED 屏幕上显示一个字符
  * @param  row  行坐标 (1 ~ 4)
  * @param  col  列坐标 (1 ~ 16)
  * @param  chr  ASCII 字符
  * @retval 无
  */
void OLED_ShowChar(u8 row, u8 col, char chr)
{
    unsigned char i;
    unsigned char page = (row - 1) * 2; // 每个8x16字符高16像素，占用2个页
    unsigned char col_pos = (col - 1) * 8; // 每个字符宽8像素
    unsigned char font_index = chr - ' ';  // 字模数组索引 (空格ASCII是32)

    // 显示上半部分 (8x8)
    OLED_SetCursor(page, col_pos);
    for (i = 0; i < 8; i++)
    {
        OLED_WriteData(OLED_F8x16[font_index][i]);
    }

    // 显示下半部分 (8x8)
    OLED_SetCursor(page + 1, col_pos);
    for (i = 0; i < 8; i++)
    {
        OLED_WriteData(OLED_F8x16[font_index][i + 8]);
    }
}

/**
  * @brief  在指定位置显示字符串
  * @param  row  行坐标 (1 ~ 4)
  * @param  col  列坐标 (1 ~ 16)
  * @param  str  字符串指针
  * @retval 无
  */
void OLED_ShowString(u8 row, u8 col, char *str)
{
    while (*str != '\0')
    {
        OLED_ShowChar(row, col, *str);
        str++;
        col++;
        if (col > 16) // 换行处理
        {
            col = 1;
            row++;
            if (row > 4) row = 1;
        }
    }
}

/**
  * @brief  显示辅助求幂函数
  */
static u32 OLED_Pow(u8 m, u8 n)
{
    u32 result = 1;
    while(n--)
    {
        result *= m;
    }
    return result;
}

/**
  * @brief  在指定位置显示无符号十进制数字
  * @param  row  行坐标 (1 ~ 4)
  * @param  col  列坐标 (1 ~ 16)
  * @param  num  无符号数 (0 ~ 65535)
  * @param  len  显示位数
  * @retval 无
  */
void OLED_ShowNum(u8 row, u8 col, u16 num, u8 len)
{
    u8 i;
    u8 temp;
    u8 show_flag = 0; // 消无效零标志位

    for (i = 0; i < len; i++)
    {
        temp = (num / OLED_Pow(10, len - i - 1)) % 10;
        
        // 消无效零逻辑：如果是高位的0，用空格代替；但如果到了个位，哪怕是0也必须显示
        if (show_flag == 0 && i < (len - 1))
        {
            if (temp == 0)
            {
                OLED_ShowChar(row, col + i, ' ');
                continue;
            }
            else
            {
                show_flag = 1;
            }
        }
        
        OLED_ShowChar(row, col + i, temp + '0');
    }
}

/**
  * @brief  在指定位置显示有符号十进制数字
  * @param  row  行坐标 (1 ~ 4)
  * @param  col  列坐标 (1 ~ 16)
  * @param  num  有符号数 (-32768 ~ 32767)
  * @param  len  显示数字位数 (不含正负号)
  * @retval 无
  */
void OLED_ShowSignedNum(u8 row, u8 col, s16 num, u8 len)
{
    u16 num_abs;
    
    if (num < 0)
    {
        OLED_ShowChar(row, col, '-'); // 显示负号
        num_abs = -num;
    }
    else
    {
        OLED_ShowChar(row, col, '+'); // 显示正号
        num_abs = num;
    }
    
    // 数字显示在符号右边
    OLED_ShowNum(row, col + 1, num_abs, len);
}
