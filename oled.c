/**
  * @brief  微秒级延时，用于I2C时序
  * @param  无
  * @retval 无
  */
static void OLED_I2C_Delay(void)
{
    // 在11.0592M或12MHz的51单片机上，执行空指令(NOP)提供微秒级延时
    unsigned char i = 4;
    while(i--);
}

/**
  * @brief  I2C 总线起始条件
  * @param  无
  * @retval 无
  */
static void OLED_I2C_Start(void)
{
    OLED_SDA = 1;
    OLED_SCL = 1;
    OLED_I2C_Delay();
    OLED_SDA = 0;
    OLED_I2C_Delay();
    OLED_SCL = 0;
    OLED_I2C_Delay();
}

/**
  * @brief  I2C 总线停止条件
  * @param  无
  * @retval 无
  */
static void OLED_I2C_Stop(void)
{
    OLED_SDA = 0;
    OLED_SCL = 1;
    OLED_I2C_Delay();
    OLED_SDA = 1;
    OLED_I2C_Delay();
}

/**
  * @brief  I2C 写入一个字节
  * @param  dat  要写入的字节数据
  * @retval 无
  */
static void OLED_I2C_WriteByte(unsigned char dat)
{
    unsigned char i;
    for (i = 0; i < 8; i++)
    {
        OLED_SDA = (dat & 0x80) ? 1 : 0;
        OLED_I2C_Delay();
        OLED_SCL = 1;
        OLED_I2C_Delay();
        OLED_SCL = 0;
        OLED_I2C_Delay();
        dat <<= 1;
    }
    // 释放SDA以接收ACK (51单片机在此处直接给1即可)
    OLED_SDA = 1;
    OLED_I2C_Delay();
    OLED_SCL = 1;
    OLED_I2C_Delay();
    OLED_SCL = 0;
    OLED_I2C_Delay();
}

